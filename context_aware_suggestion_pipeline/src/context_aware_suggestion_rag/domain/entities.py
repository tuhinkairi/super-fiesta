"""
Domain entities.

Defines the primary business objects used by the
Context-Aware Suggestion RAG pipeline.
"""

from datetime import datetime, timezone

from pydantic import BaseModel, ConfigDict, Field, HttpUrl

from context_aware_suggestion_rag.core.identifiers import (
    generate_document_id,
    generate_news_id,
    generate_recommendation_id,
    generate_trend_id,
)
from context_aware_suggestion_rag.domain.enums import (
    ContentFormat,
    DocumentType,
    RecommendationPriority,
    ProcessingStatus,
    SourceType,
)


def current_utc_time() -> datetime:
    """Return the current UTC datetime."""
    return datetime.now(timezone.utc)


class DomainEntity(BaseModel):
    """Base model shared by all domain entities."""

    model_config = ConfigDict(
        extra="forbid",
        validate_assignment=True,
        str_strip_whitespace=True,
        use_enum_values=True,
    )


class DocumentEntity(DomainEntity):
    """Represents a document supplied to the pipeline."""

    document_id: str = Field(default_factory=generate_document_id)
    filename: str = Field(min_length=1, max_length=255)
    document_type: DocumentType
    content: str = Field(min_length=1)
    language: str = Field(default="en", min_length=2, max_length=12)
    region: str = Field(default="IN", min_length=2, max_length=3)
    status: ProcessingStatus = ProcessingStatus.PENDING
    metadata: dict[str, str | int | float | bool | list[str]] = Field(
        default_factory=dict
    )
    created_at: datetime = Field(default_factory=current_utc_time)
    updated_at: datetime = Field(default_factory=current_utc_time)


class DocumentChunkEntity(DomainEntity):
    """Represents a chunk extracted from a document."""

    chunk_id: str
    document_id: str
    content: str = Field(min_length=1)
    chunk_index: int = Field(ge=0)
    metadata: dict[str, str | int | float | bool | list[str]] = Field(
        default_factory=dict
    )
    created_at: datetime = Field(default_factory=current_utc_time)


class TrendEntity(DomainEntity):
    """Represents a trending topic collected from an intelligence provider."""

    trend_id: str = Field(default_factory=generate_trend_id)
    title: str = Field(min_length=1, max_length=500)
    region: str = Field(default="IN", min_length=2, max_length=3)
    timeframe: str = Field(default="now 7-d")
    trend_score: float | None = Field(default=None, ge=0)
    collected_at: datetime = Field(default_factory=current_utc_time)
    metadata: dict[str, str | int | float | bool | list[str]] = Field(
        default_factory=dict
    )


class NewsEntity(DomainEntity):
    """Represents a news article collected from an external source."""

    news_id: str = Field(default_factory=generate_news_id)
    title: str = Field(min_length=1, max_length=500)
    url: HttpUrl
    source_name: str = Field(min_length=1, max_length=200)
    published_at: datetime | None = None
    summary: str = Field(default="", max_length=10_000)
    region: str = Field(default="IN", min_length=2, max_length=3)
    collected_at: datetime = Field(default_factory=current_utc_time)
    metadata: dict[str, str | int | float | bool | list[str]] = Field(
        default_factory=dict
    )


class RecommendationEntity(DomainEntity):
    """Represents a content recommendation generated by the pipeline."""

    recommendation_id: str = Field(default_factory=generate_recommendation_id)
    title: str = Field(min_length=1, max_length=500)
    description: str = Field(min_length=1, max_length=5000)
    rationale: str = Field(min_length=1, max_length=5000)
    source_ids: list[str] = Field(default_factory=list)
    content_format: ContentFormat
    priority: RecommendationPriority = RecommendationPriority.MEDIUM
    confidence: float | None = Field(default=None, ge=0, le=1)
    metadata: dict[str, str | int | float | bool | list[str]] = Field(
        default_factory=dict
    )
    created_at: datetime = Field(default_factory=current_utc_time)


class GeneratedContentEntity(DomainEntity):
    """Represents content generated from a recommendation."""

    content_id: str
    recommendation_id: str
    title: str = Field(min_length=1, max_length=500)
    body: str = Field(min_length=1)
    content_format: ContentFormat
    language: str = Field(default="en", min_length=2, max_length=12)
    created_at: datetime = Field(default_factory=current_utc_time)


__all__ = [
    "DomainEntity",
    "DocumentEntity",
    "DocumentChunkEntity",
    "TrendEntity",
    "NewsEntity",
    "RecommendationEntity",
    "GeneratedContentEntity",
    "current_utc_time",
]
